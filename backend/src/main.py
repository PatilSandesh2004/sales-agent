"""Main entry point for Sales Intelligence Backend (Interactive User CLI)."""

import sys
from pathlib import Path
import pandas as pd

# Ensure src is on Python path
SRC_DIR = Path(__file__).resolve().parent
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from config import DB_PATH
from infrastructure.database import load_excel_to_sqlite
from schema.query_schema import QueryRequest
from routers.query_router import handle_user_query


def ask_and_print_result(question: str):
    """Processes question through the agent and prints formatted output."""
    print("\n" + "=" * 75)
    print(f"👤 USER QUESTION: \"{question}\"")
    print("-" * 75)

    req = QueryRequest(question=question)
    response = handle_user_query(req)

    if response.plan:
        print("🧭 [PLANNER] Goal:", response.plan["goal"])
        for i, st in enumerate(response.plan["steps"], 1):
            print(f"   Step {i}: {st['description']}  ->  \"{st['sub_question']}\"")
        print()

    # Step 1: SQL generated by tool
    print("🤖 [STEP 1] GENERATED SQL QUERY (Tool: convert_query_to_sql):")
    print(f"   {response.generated_sql}\n")

    # Step 2: Data fetched from Excel/DB
    print(f"📊 [STEP 2] FETCHED DATA (Tool: execute_sql_query - {response.row_count} rows):")
    if response.data:
        df = pd.DataFrame(response.data)
        print(df.to_string(index=False))
    else:
        print("   No records returned.")

    # Step 3: Friendly answer
    print(f"\n💡 [STEP 3] AGENT ANSWER:\n   {response.summary_answer}")
    print("=" * 75 + "\n")


def main():
    print("=" * 75)
    print("🚀 SALES INTELLIGENCE AI AGENT - INTERACTIVE ASSISTANT")
    print("=" * 75)

    # 1. Initialize DB if not already present
    if not DB_PATH.exists():
        print("⚡ Database not found. Loading Excel datasets into SQLite...")
        load_excel_to_sqlite()
    else:
        print(f"🟢 Database connected at: {DB_PATH}\n")

    print("💡 Example questions you can ask:")
    print("   1. What is the total revenue generated in 2025?")
    print("   2. Which product generated the highest revenue?")
    print("   3. Which sales representative achieved the highest sales?")
    print("   4. Compare sales between Bengaluru and Mumbai.")
    print("   5. Which customers purchased more than ₹1 lakh?")
    print("   (Or type ANY custom sales question you want!)")
    print("-" * 75)

    # 2. Interactive Loop
    while True:
        try:
            user_input = input("💬 Ask a question (or type 'exit' to quit): ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\n👋 Goodbye!")
            break

        if not user_input:
            continue

        if user_input.lower() in ("exit", "quit", "q"):
            print("👋 Goodbye!")
            break

        # Allow shortcuts 1-5 for convenience
        shortcuts = {
            "1": "What is the total revenue generated in 2025?",
            "2": "Which product generated the highest revenue?",
            "3": "Which sales representative achieved the highest sales?",
            "4": "Compare sales between Bengaluru and Mumbai.",
            "5": "Which customers purchased more than ₹1 lakh?"
        }
        question = shortcuts.get(user_input, user_input)

        ask_and_print_result(question)


if __name__ == "__main__":
    main()
