"""Tools for the Sales Agent.

Tool 1 - convert_query_to_sql: the LLM writes a SQL query from the user's question
         (schema is read live from the database; no hardcoded queries anywhere).
Tool 2 - execute_sql_query:    runs the validated SQL on a read-only connection.
"""

import re
import pandas as pd
from config import GROQ_API_KEY, LLM_MODEL
from models import get_schema_text
from prompts import SQL_GENERATION_PROMPT, RETRY_BLOCK
from infrastructure.database import get_readonly_connection

MAX_RETRIES = 2  # extra attempts where the LLM sees the error and fixes its SQL

_FORBIDDEN = re.compile(
    r"\b(insert|update|delete|drop|alter|create|replace|attach|detach|pragma|vacuum|reindex|truncate)\b",
    re.IGNORECASE,
)


class SQLToolError(Exception):
    """Raised when SQL cannot be generated, is unsafe, or fails to run."""


def call_llm(prompt: str) -> str:
    """Single place that talks to the LLM (Groq)."""
    if not GROQ_API_KEY:
        raise SQLToolError(
            "GROQ_API_KEY is not set. Copy .env.example to .env and add your free key "
            "from https://console.groq.com/keys - SQL is generated by the LLM, there are no hardcoded queries."
        )
    from groq import Groq

    client = Groq(api_key=GROQ_API_KEY)
    response = client.chat.completions.create(
        messages=[{"role": "user", "content": prompt}],
        model=LLM_MODEL,
        temperature=0.0,
    )
    return response.choices[0].message.content.strip()


def clean_sql(raw: str) -> str:
    """Strips markdown fences / trailing semicolon the LLM may add."""
    raw = re.sub(r"<think>.*?</think>", "", raw, flags=re.DOTALL | re.IGNORECASE)  # reasoning models (Qwen)
    sql = re.sub(r"```(?:sql)?", "", raw, flags=re.IGNORECASE).strip()
    return sql.rstrip(";").strip()


def validate_sql(sql: str) -> None:
    """Allows only a single read-only SELECT / WITH statement."""
    if not re.match(r"^(select|with)\b", sql, re.IGNORECASE):
        raise SQLToolError("Only SELECT queries are allowed.")
    if ";" in sql:
        raise SQLToolError("Only a single SQL statement is allowed.")
    if _FORBIDDEN.search(sql):
        raise SQLToolError("Query contains a forbidden (non read-only) keyword.")


def convert_query_to_sql(user_question: str, previous_sql: str = "", error: str = "") -> str:
    """TOOL 1: plain-English question -> SQL (generated by the LLM, validated for safety)."""
    retry_block = RETRY_BLOCK.format(previous_sql=previous_sql, error=error) if error else ""
    prompt = SQL_GENERATION_PROMPT.format(
        schema_info=get_schema_text(),
        retry_block=retry_block,
        question=user_question,
    )
    sql = clean_sql(call_llm(prompt))
    validate_sql(sql)
    return sql


def execute_sql_query(sql_query: str) -> pd.DataFrame:
    """TOOL 2: runs the SQL on the read-only database. Raises SQLToolError on failure."""
    validate_sql(sql_query)
    conn = get_readonly_connection()
    try:
        return pd.read_sql_query(sql_query, conn)
    except Exception as e:
        raise SQLToolError(str(e)) from e
    finally:
        conn.close()


def ask_sales_tool(user_question: str) -> dict:
    """Generate SQL -> run it. If it fails, feed the error back to the LLM and retry."""
    sql, error = "", ""
    for attempt in range(MAX_RETRIES + 1):
        try:
            sql = convert_query_to_sql(user_question, previous_sql=sql, error=error)
            df = execute_sql_query(sql)
            return {"question": user_question, "sql": sql, "data": df,
                    "row_count": len(df), "attempts": attempt + 1}
        except SQLToolError as e:
            if "GROQ_API_KEY" in str(e):
                raise
            error = str(e)
    raise SQLToolError(f"Could not produce a working query after {MAX_RETRIES + 1} attempts. Last error: {error}")
